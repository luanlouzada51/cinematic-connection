export type TKey = keyof (typeof dict)["pt"];

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: TKey) => string };

const I18nContext = createContext<Ctx>({ lang: "pt", setLang: () => {}, t: (k) => dict.pt[k] });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("pt");

  useEffect(() => {
    const stored = window.localStorage.getItem("mm-lang") as Lang | null;
    if (stored && ["pt", "en", "es"].includes(stored)) setLangState(stored);
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    window.localStorage.setItem("mm-lang", l);
  }, []);

  const t = useCallback((k: TKey) => dict[lang][k] ?? dict.pt[k], [lang]);

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

export function genreName(
  g: { name_pt: string; name_en: string; name_es: string } | undefined,
  lang: Lang,
) {
  if (!g) return "";
  return lang === "en" ? g.name_en : lang === "es" ? g.name_es : g.name_pt;
}
